import { CONTRAST_MINIMUM, contrastRatio, formatOklch, parseOklch } from './color';
import { fontStack, listFontFaces } from './fonts';
import { motion } from './motion';
import { RADIUS_STEPS, radius } from './radius';
import { SEMANTIC_PAIRS, SEMANTIC_TOKENS, semantic, type SemanticToken } from './semantic';
import { shadow, type ShadowStep } from './shadow';
import { spacing } from './spacing';
import { STORE_FONTS, STORE_RADIUS, type StoreTheme } from './storeTheme';
import { typography } from './typography';

type Declarations = Readonly<Record<string, string>>;

const HEADER = '/* Generated by @purplerbr/tokens. Edit the TypeScript tokens, not this file. */\n';
const DARK_SELECTOR = ".dark,\n[data-theme='dark']";
const SHADOW_STEPS: readonly ShadowStep[] = ['xs', 'sm', 'md', 'lg', 'xl'];

function block(selector: string, declarations: Declarations): string {
  const body = Object.entries(declarations)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n');
  return `${selector} {\n${body}\n}\n`;
}

const colorVariables = (valueOf: (token: SemanticToken) => string): Declarations =>
  Object.fromEntries(SEMANTIC_TOKENS.map((token) => [`--${token}`, valueOf(token)]));

const brandColors = (scheme: 'light' | 'dark'): Declarations =>
  colorVariables((token) => semantic[scheme][token].oklch);

const elevationVariables = (scheme: 'light' | 'dark'): Declarations =>
  Object.fromEntries(SHADOW_STEPS.map((step) => [`--elevation-${step}`, shadow[scheme][step]]));

/** `tokens.css`: Purpler brand variables in `:root` (light) and `.dark` / `[data-theme='dark']`. */
export function renderTokensCss(): string {
  const light = {
    'color-scheme': 'light',
    ...brandColors('light'),
    '--radius': radius.base,
    '--button-radius': radius.button,
    '--font-body': typography.family.body,
    '--font-heading': typography.family.heading,
    '--font-code': typography.family.mono,
    ...elevationVariables('light'),
    ...Object.fromEntries(Object.entries(motion.duration).map(([k, v]) => [`--duration-${k}`, v])),
    ...Object.fromEntries(Object.entries(motion.easing).map(([k, v]) => [`--easing-${k}`, v])),
  };
  const dark = {
    'color-scheme': 'dark',
    ...brandColors('dark'),
    ...elevationVariables('dark'),
  };
  return `${HEADER}\n${block(':root', light)}\n${block(DARK_SELECTOR, dark)}`;
}

const offset = (px: number): string =>
  px === 0 ? 'var(--radius)' : `calc(var(--radius) ${px < 0 ? '-' : '+'} ${Math.abs(px)}px)`;

function textVariables(): Declarations {
  return Object.fromEntries(
    Object.entries(typography.scale).flatMap(([name, style]) => [
      [`--text-${name}`, style.size],
      [`--text-${name}--line-height`, style.lineHeight],
      [`--text-${name}--letter-spacing`, style.letterSpacing],
      [`--text-${name}--font-weight`, String(style.weight)],
    ])
  );
}

/** `theme.css`: maps the variables to Tailwind v4 utilities and drops Tailwind's literal scales. */
export function renderThemeCss(): string {
  const theme = {
    '--color-*': 'initial',
    ...Object.fromEntries(SEMANTIC_TOKENS.map((token) => [`--color-${token}`, `var(--${token})`])),
    '--font-*': 'initial',
    '--font-sans': 'var(--font-body)',
    '--font-display': 'var(--font-heading)',
    '--font-mono': 'var(--font-code)',
    '--font-weight-*': 'initial',
    ...Object.fromEntries(
      Object.entries(typography.weight).map(([name, value]) => [
        `--font-weight-${name === 'regular' ? 'normal' : name}`,
        String(value),
      ])
    ),
    '--radius-*': 'initial',
    ...Object.fromEntries(
      Object.entries(RADIUS_STEPS).map(([k, px]) => [`--radius-${k}`, offset(px)])
    ),
    '--radius-button': 'var(--button-radius)',
    '--shadow-*': 'initial',
    ...Object.fromEntries(
      SHADOW_STEPS.map((step) => [`--shadow-${step}`, `var(--elevation-${step})`])
    ),
    '--inset-shadow-*': 'initial',
    '--drop-shadow-*': 'initial',
    '--text-shadow-*': 'initial',
    '--ease-*': 'initial',
    ...Object.fromEntries(
      Object.keys(motion.easing).map((k) => [`--ease-${k}`, `var(--easing-${k})`])
    ),
    '--default-transition-duration': 'var(--duration-fast)',
    '--default-transition-timing-function': 'var(--easing-standard)',
    '--spacing': spacing.unit,
    '--text-*': 'initial',
    ...textVariables(),
  };
  const variant =
    "@custom-variant dark (&:where(.dark, .dark *, [data-theme='dark'], [data-theme='dark'] *));\n";
  return `${HEADER}\n${variant}\n${block('@theme inline', theme)}`;
}

/** `fonts.css`: `@font-face` rules pointing at the woff2 files shipped in `dist/fonts`. */
export function renderFontsCss(): string {
  const faces = listFontFaces().map((face) =>
    block('@font-face', {
      'font-family': `'${face.family}'`,
      'font-style': face.style,
      'font-display': 'swap',
      'font-weight': face.weight,
      src: `url('./fonts/${face.file}') format('woff2')`,
      'unicode-range': face.unicodeRange,
    })
  );
  return `${HEADER}\n${faces.join('\n')}`;
}

const ALLOWED_RADII = new Set<string>(
  Object.values(STORE_RADIUS).flatMap((r) => [r.base, r.button])
);
const ALLOWED_FONTS = new Set<string>(STORE_FONTS.map(fontStack));

type ColorSnapshot = Readonly<Record<SemanticToken, string>>;

const COLORS_ERROR = 'Store theme colors must be the OKLCH values built by buildStoreTheme';

/** Reads each color once and keeps its canonical text, so a getter or padding cannot change the output. */
function snapshotColors(colors: unknown): ColorSnapshot {
  if (typeof colors !== 'object' || colors === null) throw new TypeError(COLORS_ERROR);
  const entries = SEMANTIC_TOKENS.map((token): [SemanticToken, string] => {
    const parsed = parseOklch(Reflect.get(colors, token));
    if (parsed === null) throw new TypeError(COLORS_ERROR);
    return [token, formatOklch(parsed)];
  });
  // Object.fromEntries loses the key type; the entries above cover every semantic token.
  return Object.fromEntries(entries) as Record<SemanticToken, string>;
}

function failingPairs(scheme: string, colors: ColorSnapshot): string[] {
  return SEMANTIC_PAIRS.filter(
    ({ background, foreground, level }) =>
      contrastRatio(colors[background], colors[foreground]) < CONTRAST_MINIMUM[level]
  ).map(({ background, foreground }) => `${scheme} ${background} × ${foreground}`);
}

const isOneOf = (allowed: ReadonlySet<string>, value: unknown): value is string =>
  typeof value === 'string' && allowed.has(value);

/** CSS for a `<style>` tag over `tokens.css`; rejects foreign values and pairs below WCAG AA. */
export function renderStoreThemeCss(theme: StoreTheme): string {
  // Every field is read once and only the copies are validated and written.
  const { radius: base, buttonRadius, fontBody, fontHeading } = theme;
  const light = snapshotColors(theme.light);
  const dark = snapshotColors(theme.dark);
  if (!isOneOf(ALLOWED_RADII, base) || !isOneOf(ALLOWED_RADII, buttonRadius)) {
    throw new TypeError('Store theme radius is not one of STORE_RADIUS');
  }
  if (!isOneOf(ALLOWED_FONTS, fontBody) || !isOneOf(ALLOWED_FONTS, fontHeading)) {
    throw new TypeError('Store theme font is not one of STORE_FONTS');
  }
  const failing = [...failingPairs('light', light), ...failingPairs('dark', dark)];
  if (failing.length > 0) {
    throw new TypeError(`Store theme fails WCAG AA: ${failing.join(', ')}`);
  }
  const lightBlock = {
    ...colorVariables((token) => light[token]),
    '--radius': base,
    '--button-radius': buttonRadius,
    '--font-body': fontBody,
    '--font-heading': fontHeading,
  };
  return `${block(':root', lightBlock)}${block(
    DARK_SELECTOR,
    colorVariables((token) => dark[token])
  )}`;
}
